class NativeRuntimeConfig(unittest.TestCase):
    def test_native_config_is_valid(self):
        x = runtime_toml(NATIVE_TOML)
        b = x['deployments'][0]
        self.assertEqual((b['mode'], b['kind']), ('native', 'native_cuda'))
        validate('runtime_config', x)

    def test_native_hip_binding_is_valid(self):
        """tasks/amd-amd-spec.md PAR-6: `device_uuid = "hip:<ordinal>"` binds an AMD GPU (HIP_VISIBLE_DEVICES).
        SelfTune D3: the HIP library is the k7 MoE build; the default `p3b` is not proven on gfx1151."""
        x = runtime_toml(NATIVE_TOML)
        native = x['deployments'][0]['native']
        native['device_uuid'] = 'hip:0'
        with self.assertRaisesRegex(ContractError, "moe_gemm: 'p3b' is not proven on gfx1151"):
            validate('runtime_config', x)
        native['levers'] = {'moe_gemm': 'k7'}
        validate('runtime_config', x)
        for bad in ('hip:00', 'hip:x', 'hip:', 'hip:1234'):
            native['device_uuid'] = bad
            with self.assertRaises(ContractError):
                validate('runtime_config', x)

    def test_native_vulkan_binding_is_valid(self):
        """tasks/vulkan-amd-spec.md D2: `device_uuid = "vk:<ordinal>"` binds the Vulkan executor (arch vulkan; the
        k7 MoE build; the CUDA-only levers are refused). Rust: config_replicas.rs
        `native_vulkan_binding_is_one_replica_on_the_first_device`."""
        self.assertEqual([cere_contracts.device_arch(u) for u in ('vk:0', 'vk:12', 'hip:0', 'GPU-aaaaaaaa-0000-4000-8000-000000000000')],
                         ['vulkan', 'vulkan', 'gfx1151', 'sm_120a'])
        x = runtime_toml(NATIVE_TOML)
        native = x['deployments'][0]['native']
        native['device_uuid'] = 'vk:0'
        with self.assertRaisesRegex(ContractError, "moe_gemm: 'p3b' is not proven on vulkan"):
            validate('runtime_config', x)
        native['levers'] = {'moe_gemm': 'k7'}
        validate('runtime_config', x)
        for ordinal in ('vk:1', 'vk:12', 'vk:999'):
            native['device_uuid'] = ordinal
            validate('runtime_config', x)
        for bad in ('vk:00', 'vk:01', 'vk:x', 'vk:', 'vk:1234', 'vk:-1', 'VK:0', 'vk:0 '):
            native['device_uuid'] = bad
            with self.assertRaises(ContractError):
                validate('runtime_config', x)
        native['device_uuid'] = 'vk:0'
        for lever, impl in (('k2_gemm', 'small_m'), ('k2_gemm', 'small_m_a8'),
                            ('decode_step', 'graph'), ('decode_step', 'spec_graph'),
                            ('verify_attention', 'batched'), ('k2_weights', 'fp8')):
            native['levers'] = {'moe_gemm': 'k7', lever: impl}
            with self.assertRaisesRegex(ContractError, f"^deployments\\[0\\]\\.native\\.levers\\.{lever}: '{impl}' is not proven on vulkan"):
                validate('runtime_config', x)
        # `p4` is the Vulkan FP16 cooperative-matrix prefill attention: accepted on vulkan, still refused on HIP.
        native['levers'] = {'moe_gemm': 'k7', 'prefill_attention': 'p4'}
        validate('runtime_config', x)
        native['device_uuid'] = 'hip:0'
        with self.assertRaisesRegex(ContractError, "^deployments\\[0\\]\\.native\\.levers\\.prefill_attention: 'p4' is not proven on gfx1151"):
            validate('runtime_config', x)

