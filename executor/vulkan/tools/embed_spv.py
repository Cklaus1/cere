#!/usr/bin/env python3
"""Generate the embedded SPIR-V table of the Vulkan launch layer (conductor decision OD-4: the library's sha256 covers
its shaders).

    python3 executor/vulkan/tools/embed_spv.py <spv_dir> <out.cpp>

Writes one C++ translation unit that pulls every <spv_dir>/*.spv into .rodata with the assembler's .incbin (no hex
text, so the compile stays fast) and defines the table `cere_vk_embedded_spv[]` / `cere_vk_embedded_spv_count`
(name, words, bytes, sha256) that vk_launch.cpp declares weak. Deterministic: modules sorted by name (byte order),
no timestamps, no absolute paths beyond the <spv_dir> given (relative to the compiler's working directory: compile the
output from the same directory this script was run from). The .incbin path is not part of the object.
"""
import hashlib
import os
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    spv_dir, out = sys.argv[1], sys.argv[2]
    names = sorted((n for n in os.listdir(spv_dir) if n.endswith(".spv")), key=lambda n: n.encode())
    if not names:
        print(f"embed_spv: no .spv under {spv_dir}", file=sys.stderr)
        return 1
    rows = []
    for i, n in enumerate(names):
        if '"' in n or "\\" in n:
            print(f"embed_spv: unsupported file name {n!r}", file=sys.stderr)
            return 1
        data = open(os.path.join(spv_dir, n), "rb").read()
        if len(data) < 20 or len(data) % 4 or data[:4] != b"\x03\x02\x23\x07":
            print(f"embed_spv: {n} is not a little-endian SPIR-V module", file=sys.stderr)
            return 1
        rows.append((i, n, len(data), hashlib.sha256(data).hexdigest()))
    lines = [
        "// GENERATED by executor/vulkan/tools/embed_spv.py: do not edit. "
        f"{len(rows)} SPIR-V modules, sorted by name.",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        '#include "launch/vk_launch.h"',
        "",
        'asm(".pushsection .rodata.cere_vk_spv,\\"a\\",@progbits\\n"',
    ]
    for i, n, _, _ in rows:
        path = os.path.join(spv_dir, n)
        lines.append(f'    ".balign 16\\ncere_vk_spv_{i}:\\n.incbin \\"{path}\\"\\n"')
    lines.append('    ".popsection\\n");')
    lines.append("")
    lines.append('extern "C" {')
    for i, _, _, _ in rows:
        lines.append(f'__attribute__((visibility("hidden"))) extern const uint32_t cere_vk_spv_{i}[];')
    lines.append("extern const cere::vk::EmbeddedShader cere_vk_embedded_spv[] = {")
    for i, n, size, sha in rows:
        lines.append(f'    {{"{n}", cere_vk_spv_{i}, {size}u, "{sha}"}},')
    lines.append("};")
    lines.append(f"extern const size_t cere_vk_embedded_spv_count = {len(rows)};")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    os.replace(tmp, out)
    total = sum(r[2] for r in rows)
    print(f"embed_spv: {len(rows)} modules, {total} bytes -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
